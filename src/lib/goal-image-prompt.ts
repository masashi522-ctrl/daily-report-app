// 利用者管理の「ゴールのイメージ」をAIに提案させるためのプロンプト。
//
// ゴールのイメージは介護のACPの取り組みで使う言葉で、長期目標の上位にあたるものです。
// 長期目標から機械的に導けるものではないため、介護計画書の全体を材料にして
// 「なんのためにこの目標があるのか」を考えさせます。
// 生成の質がプロンプトの書き方に強く依存するので、APIルートから切り出して
// scripts から同じ文面を試せるようにしています。

// この事業所の形体。将来的に施設ごとに設定できるようにする場合はここを差し替える
export const FACILITY_TYPE = '通所介護（デイサービス）'

export interface Suggestion {
  main: string
  subs: string[]
}

export interface GoalImageMaterials {
  /** 介護計画書の内容をまとめたもの。課題分析・援助方針・援助目標など */
  carePlanContext?: string
  /** 担当職員が書いた、現時点のゴールのイメージ（仮） */
  goalImage?: string
  /** すでに入力済みのサブのゴールのイメージ */
  subGoalImage?: string
  /** 「男」「女」または未設定 */
  gender?: string
}

// 介護計画書の1行分。通常様式と予防様式で項目名が違うため両方を受ける
interface PlanGoalLike {
  issue?: string
  longTermGoal?: string
  shortTermGoal?: string
  goal?: string
  supportPoint?: string
  serviceContent?: string
  frequency?: string
  period?: string
}

interface CarePlanLike {
  careLevel?: string | null
  needsAnalysis?: string | null
  supportPolicy?: string | null
  healthNotes?: string | null
  dailyGoal?: string | null
  yearlyGoal?: string | null
  programs?: string | null
  goals?: PlanGoalLike[] | null
  evaluationContent?: string | null
  goalImage?: string | null
}

function formatGoal(g: PlanGoalLike, i: number): string {
  const rows: [string, string | undefined][] = [
    ['課題・ニーズ', g.issue],
    ['長期目標', g.longTermGoal],
    ['短期目標', g.shortTermGoal],
    ['目標', g.goal],
    ['支援のポイント', g.supportPoint],
    ['サービス内容', g.serviceContent],
    ['頻度', g.frequency],
    ['期間', g.period],
  ]
  const body = rows
    .filter(([, v]) => (v ?? '').trim())
    .map(([label, v]) => `    ${label}: ${v!.trim()}`)
    .join('\n')
  return body ? `  (${i + 1})\n${body}` : ''
}

// 介護計画書を、ひとつながりの生活として読める形にまとめる。
// 長期目標だけを渡すと「なんのための目標か」を考える手がかりが無くなるため、
// 課題分析・援助方針・サービス内容・評価まで含める。
export function formatCarePlanContext(plan: CarePlanLike | null): string {
  if (!plan) return ''

  const goals = (plan.goals ?? []).map(formatGoal).filter(Boolean)

  return [
    plan.careLevel ? `要介護度: ${plan.careLevel}` : '',
    plan.needsAnalysis ? `課題分析の結果:\n${plan.needsAnalysis}` : '',
    plan.supportPolicy ? `総合的な援助の方針:\n${plan.supportPolicy}` : '',
    plan.healthNotes ? `健康状態:\n${plan.healthNotes}` : '',
    plan.dailyGoal ? `1日の目標: ${plan.dailyGoal}` : '',
    plan.yearlyGoal ? `1年後の目標: ${plan.yearlyGoal}` : '',
    plan.programs ? `必要な事業プログラム: ${plan.programs}` : '',
    goals.length > 0 ? `援助目標:\n${goals.join('\n')}` : '',
    plan.evaluationContent ? `サービス達成状況の評価:\n${plan.evaluationContent}` : '',
    plan.goalImage ? `計画書に記載済みのゴールのイメージ:\n${plan.goalImage}` : '',
  ].filter(Boolean).join('\n\n')
}

export function buildMaterials(m: GoalImageMaterials): string {
  return [
    m.carePlanContext
      ? ['【介護計画書】', m.carePlanContext].join('\n')
      : '',
    m.goalImage
      ? ['【担当職員が書いた、現時点のゴールのイメージ（仮）】', m.goalImage].join('\n')
      : '',
    m.subGoalImage
      ? ['【すでに入力済みのサブのゴールのイメージ】（これらと重複しない内容を提案してください）', m.subGoalImage].join('\n')
      : '',
  ].filter(Boolean).join('\n\n')
}

